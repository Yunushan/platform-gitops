#!/usr/bin/env python3
"""Optional Gerrit success reporting for an explicitly trusted Jenkins setup.

The Jenkins controller, job configuration, workers and plugins are part of the
trust boundary. The available evidence does not independently attest checkout
or prove that a job configuration was unchanged throughout a build.
"""
import argparse
import base64
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import quote
from urllib.request import Request

from bounded_file import read_bounded_text
from http_transport import open_http_request, read_bounded_response
from strict_json import loads_strict_json
from tekton_forge_bridge import private_input
import resolve_jenkins_gerrit_build as resolver
import tekton_gerrit_bridge as bridge
import tekton_gerrit_reporter as reporter
import trigger_jenkins_gerrit as trigger
import verify_jenkins_gerrit as verifier


def validate(plan):
    fields = {"schema_version", "trigger", "reviewer_username", "reviewer_account_id",
              "label_definition_sha256", "trust_jenkins_controller"}
    if not isinstance(plan, dict) or set(plan) != fields or type(plan["schema_version"]) is not int or plan["schema_version"] != 1:
        raise ValueError("invalid-report-policy")
    trigger.validate(plan["trigger"])
    if plan["trust_jenkins_controller"] is not True:
        raise ValueError("explicit-jenkins-trust-required")
    if not isinstance(plan["reviewer_username"], str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,99}", plan["reviewer_username"]):
        raise ValueError("invalid-reviewer")
    if type(plan["reviewer_account_id"]) is not int:
        raise ValueError("invalid-reviewer-account")
    bridge.number(plan["reviewer_account_id"])
    if not isinstance(plan["label_definition_sha256"], str) or not re.fullmatch(r"[0-9a-f]{64}", plan["label_definition_sha256"]):
        raise ValueError("invalid-label-digest")
    return plan


def report_identity(plan, result, *, failure=False):
    t = plan["trigger"]
    identity_input = {"policy": plan, "queue_id": result["queue_id"], "build": result["build"]}
    if failure: identity_input["result"] = "FAILURE"
    identity = reporter.fingerprint(identity_input)
    payload = {"message": "Jenkins %s; build %s; queue %s; revision %s" % ("failure" if failure else "success", result["build"], result["queue_id"], t["revision"]),
               "tag": "autogenerated:platform-jenkins:" + identity[:32], "labels": {"Verified": -1 if failure else 1},
               "notify": "NONE", "drafts": "KEEP", "omit_duplicate_comments": True,
               "ignore_automatic_attention_set_rules": True}
    expected = {"schema_version": 1, "identity_sha256": identity, "payload_sha256": reporter.fingerprint(payload)}
    return identity, payload, expected


def read_reservation(path):
    try:
        fd = os.open(path, os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0))
    except FileNotFoundError:
        return None
    with os.fdopen(fd, "rb") as stream:
        data = stream.read(4097)
    if len(data) > 4096: raise ValueError("invalid-review-reservation")
    return loads_strict_json(data)


def report(plan, queue_journal, review_journal_dir, jenkins_get, gerrit_get, api, *, apply=False, failure=False):
    """Check evidence and optionally publish one result vote, at most once.

    An uncertain write is never retried automatically. An existing reservation
    can only be reconciled by observing the exact tagged Gerrit vote.
    """
    validate(plan)
    if type(apply) is not bool or type(failure) is not bool: raise ValueError("invalid-mode")
    t = plan["trigger"]
    original = {"source": {"project": t["project"], "branch": t["branch"]}}
    settings = {"account_id": plan["reviewer_account_id"], "http_username": plan["reviewer_username"],
                "label_definition_sha256": plan["label_definition_sha256"]}
    item = {"change": t["change"], "patchset": t["patchset"], "revision": t["revision"],
            "ref": bridge.reference(t["change"], t["patchset"])}
    directory = trigger.private_journal_directory(review_journal_dir)

    def check():
        result = (resolver.resolve_failure(t, queue_journal, jenkins_get, gerrit_get) if failure
                  else resolver.resolve(t, queue_journal, jenkins_get, gerrit_get))
        evidence = result.get("evidence", {})
        if (result.get("status") != ("matched-failure" if failure else "matched-success") or result.get("build_verified") is not True
                or evidence.get("queue_identity_verified") is not True
                or evidence.get("job_config_reservation_verified") is not True):
            raise ValueError("config-bound-success-required")
        reporter.source_policy(api, original, settings)
        return result, reporter.review(api, original, item)

    result, obj = check()
    identity, payload, expected = report_identity(plan, result, failure=failure)
    path = directory / (identity + ".json")
    published = reporter.published(obj, settings, item, payload)
    record = read_reservation(path)
    if record is not None:
        if record != expected: raise ValueError("invalid-review-reservation")
        if not published: raise ValueError("review-outcome-uncertain-do-not-retry")
        return {"status": "already-reported", "review_vote_verified": True, "checkout_provenance_verified": False}
    if published: raise ValueError("unreserved-existing-review")
    if not apply:
        return {"status": "ready", "review_vote_verified": False, "checkout_provenance_verified": False}
    repeated, obj = check()
    if repeated != result or reporter.published(obj, settings, item, payload):
        raise ValueError("review-evidence-changed")
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(path, flags, 0o600)
    with os.fdopen(fd, "wb") as stream:
        stream.write(json.dumps(expected, sort_keys=True).encode("utf-8"))
        stream.flush()
        os.fsync(stream.fileno())
    if os.name == "posix":
        dfd = os.open(directory, os.O_RDONLY)
        try: os.fsync(dfd)
        finally: os.close(dfd)
    api.request("/a/changes/%s/revisions/%s/review" % (t["change"], t["revision"]), payload)
    reporter.source_policy(api, original, settings)
    if not reporter.published(reporter.review(api, original, item), settings, item, payload):
        raise ValueError("review-not-observed-do-not-retry")
    return {"status": "reported", "review_vote_verified": True, "checkout_provenance_verified": False}


def verify_merged(plan, queue_journal, review_journal_dir, jenkins_get, gerrit_get, api):
    """Read-only check of a reported build and its exact current merged head."""
    validate(plan)
    t = plan["trigger"]
    original = {"source": {"project": t["project"], "branch": t["branch"]}}
    settings = {"account_id": plan["reviewer_account_id"], "http_username": plan["reviewer_username"],
                "label_definition_sha256": plan["label_definition_sha256"]}
    item = {"change": t["change"], "patchset": t["patchset"], "revision": t["revision"],
            "ref": bridge.reference(t["change"], t["patchset"])}
    directory = trigger.private_journal_directory(review_journal_dir)
    def check():
        result = resolver.resolve(t, queue_journal, jenkins_get, gerrit_get, change_state="MERGED")
        evidence = result.get("evidence", {})
        if (result.get("status") != "matched-success" or result.get("build_verified") is not True
                or evidence.get("queue_identity_verified") is not True
                or evidence.get("job_config_reservation_verified") is not True):
            raise ValueError("config-bound-success-required")
        reporter.source_policy(api, original, settings)
        obj = api.request("/a/changes/" + str(t["change"]) + "/detail?o=CURRENT_REVISION&o=DETAILED_LABELS&o=MESSAGES")
        if bridge.current(original, obj, status="MERGED") != item: raise ValueError("merged-revision-changed")
        identity, payload, expected = report_identity(plan, result)
        if read_reservation(directory / (identity + ".json")) != expected:
            raise ValueError("matching-review-reservation-required")
        if not reporter.published(obj, settings, item, payload): raise ValueError("success-vote-not-observed")
        return result
    verified = check()
    if verified != check(): raise ValueError("merged-evidence-changed")
    return {"status": "merged-evidence-matched", "read_only": True, "review_vote_verified": True,
            "change": t["change"], "patchset": t["patchset"], "revision": t["revision"],
            "queue_id": verified["queue_id"], "build": verified["build"],
            "report_policy_sha256": reporter.fingerprint(plan),
            "checkout_provenance_verified": False, "deployment_authorized": False, "full_stack_verified": False}


class ReviewAPI:
    """Limit the reviewer credential to the policy's single change and project."""
    def __init__(self, plan, token, *, tls_context=None):
        self.trigger = plan["trigger"]
        self.tls_context = tls_context
        self.authorization = "Basic " + base64.b64encode(plan["reviewer_username"].encode("ascii") + b":" + token).decode("ascii")

    def request(self, path, payload=None):
        t = self.trigger
        reads = {"/a/accounts/self", "/a/projects/" + quote(t["project"], safe="") + "/labels/?inherited",
                 "/a/changes/" + str(t["change"]) + "/detail?o=CURRENT_REVISION&o=DETAILED_LABELS&o=MESSAGES"}
        write = "/a/changes/%s/revisions/%s/review" % (t["change"], t["revision"])
        if payload is None:
            if path not in reads: raise ValueError("review-resource-outside-policy")
        elif (path != write or not isinstance(payload, dict) or set(payload) != {"message", "tag", "labels", "notify", "drafts", "omit_duplicate_comments", "ignore_automatic_attention_set_rules"}
              or not isinstance(payload.get("labels"), dict) or set(payload["labels"]) != {"Verified"}
              or type(payload["labels"]["Verified"]) is not int or payload["labels"]["Verified"] not in {-1, 1}
              or payload.get("notify") != "NONE" or payload.get("drafts") != "KEEP"
              or payload.get("omit_duplicate_comments") is not True or payload.get("ignore_automatic_attention_set_rules") is not True
              or not isinstance(payload.get("message"), str) or not isinstance(payload.get("tag"), str)):
            raise ValueError("review-write-outside-policy")
        data = bridge.common.canonical(payload) if payload is not None else None
        request = Request(t["gerrit_origin"] + path, data=data,
                          headers={"Authorization": self.authorization, "Accept": "application/json", "Content-Type": "application/json"})
        with open_http_request(request, timeout=15, use_environment_proxy=False, tls_context=self.tls_context) as response:
            raw = read_bounded_response(response, max_bytes=1024 * 1024)
        if not raw.startswith(b")]}'\n"): raise ValueError("invalid-gerrit-response")
        return loads_strict_json(raw[5:])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--queue-journal", type=Path, required=True)
    parser.add_argument("--review-journal-dir", type=Path, required=True)
    parser.add_argument("--input-dir", type=Path, required=True)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true", help="Publish a verified success vote")
    mode.add_argument("--verify-merged", action="store_true", help="Read-only check of the reported merged branch head")
    parser.add_argument("--failure", action="store_true", help="Select a definite failed build for a negative review")
    args = parser.parse_args()
    try:
        plan = validate(loads_strict_json(read_bounded_text(args.plan, max_bytes=16384)))
        users = [private_input(n, minimum=1, maximum=100, root=args.input_dir).decode("ascii")
                 for n in ("jenkins-user", "gerrit-user", "reviewer-user")]
        if (any(not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,99}", u) for u in users)
                or users[1].casefold() == users[2].casefold() or users[2] != plan["reviewer_username"]):
            raise ValueError("separate-reviewer-required")
        tokens = [private_input(n, minimum=16, maximum=512, root=args.input_dir)
                  for n in ("jenkins-token", "gerrit-token", "reviewer-token")]
        if any(any(c < 33 or c > 126 for c in token) for token in tokens): raise ValueError("invalid-token")
        private_input("ca.crt", maximum=256 * 1024, root=args.input_dir)
        os.environ["SSL_CERT_FILE"] = str(args.input_dir / "ca.crt")
        t = plan["trigger"]
        arguments = (plan, args.queue_journal, args.review_journal_dir,
                     verifier.requester(t["jenkins_origin"], users[0], tokens[0]),
                     verifier.requester(t["gerrit_origin"], users[1], tokens[1], prefix=True), ReviewAPI(plan, tokens[2]))
        if args.verify_merged and args.failure: raise ValueError("failure-cannot-authorize-merged-check")
        result = verify_merged(*arguments) if args.verify_merged else report(*arguments, apply=args.apply, failure=args.failure)
    except Exception:
        print("Jenkins report failed; check private evidence and any existing reservation before retrying.", file=sys.stderr)
        return 1
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__": sys.exit(main())
